const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const canvas=require('@napi-rs/canvas');
Object.assign(globalThis,{DOMMatrix:canvas.DOMMatrix,ImageData:canvas.ImageData,Path2D:canvas.Path2D});
exports.compact=text=>text.replace(/\s+/g,'');
exports.parse=async bytes=>{
 assert.equal(Buffer.from(bytes).subarray(0,5).toString(),'%PDF-');
 assert.ok(Buffer.from(bytes).subarray(-15).toString().includes('%%EOF'));
 const {getDocument}=await import('pdfjs-dist/legacy/build/pdf.mjs');
 const pdf=await getDocument({data:new Uint8Array(bytes),isEvalSupported:false,useSystemFonts:false}).promise;
 const pages=[];
 for(let i=1;i<=pdf.numPages;i++){
  const page=await pdf.getPage(i),content=await page.getTextContent();
  pages.push({page,items:content.items.filter(item=>'str' in item),text:content.items.map(item=>item.str||'').join(' ')});
 }
 return {pdf,pages,text:pages.map(page=>page.text).join('\n')};
};
exports.assertLayout=parsed=>{
 for(const [index,{page,items,text}]of parsed.pages.entries()){
  const viewport=page.getViewport({scale:1});
  assert.ok(text.includes('Generated by SiteTrace'));
  assert.ok(text.includes('Page '+(index+1)+' of '+parsed.pages.length));
  for(const item of items.filter(item=>item.str.trim())){
   const [,,,,x,y]=item.transform;
   assert.ok(x>=37 && x+item.width<=viewport.width-37,`Horizontal clipping: ${item.str} at ${x} width ${item.width}`);
   assert.ok(y>=20 && y<=viewport.height-25,`Vertical clipping: ${item.str} at ${y}`);
   // Body text must stay between the running title/rule and footer.
   if(y<viewport.height-95 && y>35)assert.ok(y>=53,'Body overlaps footer: '+item.str);
  }
  const visible=items.filter(item=>item.str.trim()&&item.width>0);
  for(let i=0;i<visible.length;i++)for(let j=i+1;j<visible.length;j++){
   const a=visible[i],b=visible[j];
   const overlapX=Math.min(a.transform[4]+a.width,b.transform[4]+b.width)-Math.max(a.transform[4],b.transform[4]);
   const overlapY=Math.min(a.transform[5]+a.height,b.transform[5]+b.height)-Math.max(a.transform[5],b.transform[5]);
   assert.ok(overlapX<0.7||overlapY<0.7,'Overlapping PDF text: '+a.str+' / '+b.str);
  }
 }
};
exports.render=async(parsed,directory,name,pages=[1])=>{
 fs.mkdirSync(directory,{recursive:true});
 for(const number of pages){
  const page=parsed.pages[number-1].page,viewport=page.getViewport({scale:1.5});
  const surface=canvas.createCanvas(Math.ceil(viewport.width),Math.ceil(viewport.height));
  await page.render({canvasContext:surface.getContext('2d'),viewport,canvas:surface}).promise;
  fs.writeFileSync(path.join(directory,name+'-page-'+number+'.png'),surface.toBuffer('image/png'));
 }
};
exports.capture=async({evaluate,click,wait},selector='#report-export')=>{
 await evaluate(`(()=>{window.__pdfCapture={create:URL.createObjectURL,click:HTMLAnchorElement.prototype.click};URL.createObjectURL=blob=>{__pdfCapture.blob=blob;return __pdfCapture.create.call(URL,blob)};HTMLAnchorElement.prototype.click=function(){__pdfCapture.filename=this.download}})()`);
 try{
  await click(selector);await wait('!!window.__pdfCapture.blob && !SiteTracePDF.busy');
  const result=await evaluate(`(async()=>{const bytes=new Uint8Array(await __pdfCapture.blob.arrayBuffer());let raw='';for(const byte of bytes)raw+=String.fromCharCode(byte);return {base64:btoa(raw),filename:__pdfCapture.filename,type:__pdfCapture.blob.type};})()`);
  const bytes=Buffer.from(result.base64,'base64');
  assert.equal(result.type,'application/pdf');
  const parsed=await exports.parse(bytes);
  return {...result,...parsed,bytes};
 }finally{await evaluate('URL.createObjectURL=__pdfCapture.create;HTMLAnchorElement.prototype.click=__pdfCapture.click;delete window.__pdfCapture');}
};
