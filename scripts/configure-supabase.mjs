// Generate browser configuration from an explicit allowlist. Never copy server keys.
import {readFile, writeFile, rm} from 'node:fs/promises';
import {parseEnv} from 'node:util';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';

export const root = fileURLToPath(new URL('../', import.meta.url));
export const output = new URL('../js/supabase-config.js', import.meta.url);

export async function readConfiguration() {
  let local = {};
  try { local = parseEnv(await readFile(new URL('../.env', import.meta.url), 'utf8')); }
  catch (error) { if (error.code !== 'ENOENT') throw new Error('Could not read the root .env file.'); }
  // Explicit shell variables support hosting/CI; .env supplies local defaults.
  return {...local, ...process.env};
}

export function publicConfiguration(env) {
  let url;
  try { url = new URL(env.SUPABASE_URL); } catch (_) { throw new Error('Set SUPABASE_URL in the root .env file.'); }
  if ((url.protocol !== 'https:' && !(url.protocol === 'http:' && ['localhost', '127.0.0.1', '[::1]'].includes(url.hostname))) || url.username || url.password || url.search || url.hash || url.pathname !== '/') {
    throw new Error('SUPABASE_URL must be the HTTPS project origin (HTTP is allowed for localhost).');
  }
  const key = (env.SUPABASE_PUBLISHABLE_KEY || env.SUPABASE_ANON_KEY || '').trim();
  let payload;
  try { payload = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString()); } catch (_) {}
  if (!/^sb_publishable_[A-Za-z0-9_-]+$/.test(key) && payload?.role !== 'anon') {
    throw new Error('Set SUPABASE_PUBLISHABLE_KEY to the project publishable key (or SUPABASE_ANON_KEY to its legacy anon key). Never use a secret/service-role key.');
  }
  const ref = url.hostname.match(/^([a-z0-9]+)\.supabase\.co$/)?.[1];
  if (payload?.ref && ref && payload.ref !== ref) throw new Error('The anon key belongs to a different Supabase project.');
  return {supabaseUrl: url.origin, supabasePublishableKey: key};
}

export async function configure() {
  try {
    const config = publicConfiguration(await readConfiguration());
    await writeFile(output, '// Generated by npm run configure. Contains public configuration only.\nwindow.MCPA_CONFIG = Object.freeze(' + JSON.stringify(config, null, 2) + ');\n');
    return config;
  } catch (error) {
    // An invalid switch must never leave the previous database active.
    await rm(output, {force: true});
    throw error;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  configure().then(config => console.log(`Browser configuration updated: ${config.supabaseUrl}`)).catch(error => { console.error(error.message); process.exitCode = 1; });
}
